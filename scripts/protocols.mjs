// Makes the protocols' types and checks from ai-platform's schemas, pinned at platform/
// (docs/decisions/0004-talking-to-the-cloud.md):
//
//   npm run protocols              writes them into src/shared/protocols/generated/
//   npm run protocols -- --check   fails if they differ from what is there (CI)
//
// The types cover every definition, and so do the checks: Ajv's standalone code, made here, so
// that nothing is compiled while the app runs. The app checks every body it receives, and the
// simulated cloud every body it is sent, as the cloud does; screens check what people type.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const prettier = require('prettier');
const { compile } = require('json-schema-to-typescript');
const Ajv2020 = require('ajv/dist/2020').default;
const standaloneCode = require('ajv/dist/standalone').default;

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PLATFORM = join(ROOT, 'platform', 'protocols');
const OUT = join(ROOT, 'src', 'shared', 'protocols', 'generated');
// Each protocol the app speaks, and the definitions of its schema that only tell bodies apart:
// each endpoint knows which body it takes and gives, so they get no check of their own.
const PROTOCOLS = [{ name: 'app', tellers: ['from_app', 'from_cloud'] }];
// The identifier the schemas are given here, for Ajv to resolve their references: any URI.
const BASE = 'https://ai-platform.invalid/protocols/';
// Ajv's own strictness, but for strictRequired: a `then` may require a property that its
// parent declares, as the app API's member does, which JSON Schema allows.
const AJV_OPTIONS = { code: { source: true, esm: true }, strict: true, strictRequired: false };
const VERSION = /version (\d+\.\d+)/;

/** The definitions to check: every one, but the tellers, which must be definitions too. */
function checkedDefinitions(schema, tellers) {
  for (const teller of tellers) {
    if (!(teller in schema.$defs)) {
      throw new Error(`${teller}: expected a definition, which tells bodies apart`);
    }
  }
  return Object.keys(schema.$defs).filter((name) => !tellers.includes(name));
}

/** The name json-schema-to-typescript gives a definition: `home_list` is `HomeList`. */
function typeName(definition) {
  return definition
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
}

async function format(source, file) {
  const options = await prettier.resolveConfig(file);
  return prettier.format(source, { ...options, filepath: file });
}

/** The files to write for `protocol`, by path. */
async function generate({ name, tellers }) {
  const path = join(PLATFORM, name, 'schema.json');
  const schema = JSON.parse(readFileSync(path, 'utf8'));
  const version = VERSION.exec(schema.title ?? '')?.[1];
  if (!version) {
    throw new Error(`${path}: its title gives no version`);
  }
  const id = `${BASE}${name}/schema.json`;
  const banner =
    '// SPDX-License-Identifier: MIT\n' +
    `// Generated by scripts/protocols.mjs from platform/protocols/${name}/schema.json, ` +
    `version ${version} (ADR-0004). Do not edit.\n`;
  const definitions = checkedDefinitions(schema, tellers);

  const types = await compile({ ...schema, $id: id }, typeName(name), {
    bannerComment: '',
    unreachableDefinitions: true,
    additionalProperties: true,
    // A list's bounds are its check's to enforce: its type is an array, not a union of tuples.
    ignoreMinAndMaxItems: true,
    format: false,
  });
  for (const definition of definitions) {
    if (!new RegExp(`^export (interface|type) ${typeName(definition)}\\b`, 'm').test(types)) {
      throw new Error(`${name}: no type ${typeName(definition)} for ${definition}`);
    }
  }

  const ajv = new Ajv2020(AJV_OPTIONS);
  ajv.addSchema({ ...schema, $id: id });
  const checks = standaloneCode(
    ajv,
    Object.fromEntries(definitions.map((definition) => [definition, `${id}#/$defs/${definition}`])),
  );

  const declarations = [
    banner,
    "import type { ErrorObject } from 'ajv';",
    '',
    `import type * as Types from './${name}';`,
    '',
    '/** A check of one definition: whether `data` is one, and why not. */',
    'export interface Check<T> {',
    '  (data: unknown): data is T;',
    '  errors?: ErrorObject[] | null;',
    '}',
    '',
    ...definitions.map(
      (definition) => `export declare const ${definition}: Check<Types.${typeName(definition)}>;`,
    ),
    '',
  ].join('\n');

  const files = {
    [join(OUT, `${name}.ts`)]: banner + '\n' + types,
    [join(OUT, `${name}-checks.d.ts`)]: declarations,
    [join(OUT, `${name}-checks.js`)]: banner + checks + '\n',
  };
  for (const [file, source] of Object.entries(files)) {
    if (file.endsWith('.ts')) {
      files[file] = await format(source, file);
    }
  }
  return files;
}

async function main() {
  const check = process.argv.includes('--check');
  const stale = [];
  for (const protocol of PROTOCOLS) {
    for (const [file, source] of Object.entries(await generate(protocol))) {
      let current = null;
      try {
        current = readFileSync(file, 'utf8');
      } catch {
        current = null;
      }
      if (current === source) {
        continue;
      }
      if (check) {
        stale.push(relative(ROOT, file));
      } else {
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, source);
        console.log(`wrote ${relative(ROOT, file)}`);
      }
    }
  }
  if (stale.length > 0) {
    console.error(`not what platform/'s schemas make (run npm run protocols): ${stale.join(', ')}`);
    process.exit(1);
  }
}

await main();
